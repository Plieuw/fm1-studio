import math
SR=44100; CTRL=8
o=["/* generated by gen_tables.py - do not edit */\n#include <stdint.h>\n#ifndef AJ_DATA\n#define AJ_DATA\n#endif\n"]
def arr(name,typ,vals,extra=""):
    o.append("static const %s %s[%d] AJ_DATA={%s};\n"%(typ,name,len(vals),",".join(map(str,vals))))
arr("aj_inc","uint32_t",[min(0x7FFFFFFF,round(440*2**((n-69)/12)/SR*2**32)) for n in range(128)])
arr("aj_exp2","uint32_t",[round(2**(i/256)*2**30) for i in range(257)])
N=360
o.append("#define AJ_LPG_N %d\n"%N)
arr("aj_lpg","uint32_t",[round((1-math.exp(-2*math.pi*min(16*2**(i/32),0.2*SR)/SR))*2**30) for i in range(N)])
arr("aj_ticks","uint32_t",[max(1,round(0.0015*(10/0.0015)**(i/127)*SR/CTRL)) for i in range(128)])
arr("aj_lfo_inc","uint32_t",[round(0.05*(900)**(i/127)*CTRL/SR*2**32) for i in range(128)])   # main LFO 0.05..45 Hz (per control tick)
arr("aj_pwm_inc","uint32_t",[round(0.1*(200)**(i/127)*CTRL/SR*2**32) for i in range(128)])   # PWM LFO 0.1..20 Hz (per control tick)
arr("aj_hpf_g","uint32_t",[round((1-math.exp(-2*math.pi*fc/SR))*2**30) for fc in (120,0.0001,240,720)])
dly=[0]+[round(0.05*(80)**(i/127)*SR/CTRL) for i in range(1,128)]
arr("aj_dly_step","uint32_t",[65536 if t==0 else 65536//t+1 for t in dly])
arr("aj_lvl","uint32_t",[round(i*2**24/127) for i in range(128)])          # level 0..127 -> Q24
arr("aj_recip","uint32_t",[round(2**38/(128+i)) for i in range(129)])     # 2^62/m table for division-free reciprocal
arr("aj_cho_inc","uint32_t",[round(0.1*(200)**(i/127)/SR*2**32) for i in range(128)])   # chorus LFO 0.1..20 Hz per sample
open("aj_tables.h","w").write("".join(o)); print("tables ok")
