def code(c):
    if 'A'<=c<='Z': return ord(c)-65
    if 'a'<=c<='z': return 26+ord(c)-97
    if '0'<=c<='9': return 52+ord(c)-48
    if c=='-': return 63
    return 62
rows=[]; syx=bytearray()
for name,d in P:
    p=dict(BASE); p.update(d)
    for k in d: assert k in BASE,k
    v=[p[k] for k in N]; rows.append((name,v))
    nm=(name+" "*10)[:10]
    syx+=bytes([0xF0,0x41,0x35,0x00,0x23,0x20,0x01])+bytes(v)+bytes(code(c) for c in nm)+b"\xF7"
assert len(syx)==54*len(P)
o=["/* generated by gen_presets.py - do not edit */\n#include <stdint.h>\n#ifndef AJ_DATA\n#define AJ_DATA\n#endif\n",
   "#define AJ_NPRESETS %d\n"%len(P),
   "static const uint8_t aj_presets[AJ_NPRESETS][36] AJ_DATA = {\n"+",\n".join("  {"+",".join(map(str,v))+"} /* %s */"%n for n,v in rows)+"\n};\n"]
open("aj_presets.h","w").write("".join(o)); open("presets.syx","wb").write(syx); print("ok",len(syx))
